CREATE TABLE menu_stock (
 menu_item_id VARCHAR(100) PRIMARY KEY, remaining_quantity INTEGER NOT NULL CHECK (remaining_quantity >= 0), version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE recommendation_sets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL REFERENCES conversations(id),
 assistant_message_id BIGINT NOT NULL UNIQUE REFERENCES messages(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX recommendation_latest ON recommendation_sets(conversation_id, id);
CREATE TABLE recommendation_set_items (
 recommendation_set_id BIGINT NOT NULL REFERENCES recommendation_sets(id),
 menu_item_id VARCHAR(100) NOT NULL REFERENCES menu_stock(menu_item_id),
 PRIMARY KEY (recommendation_set_id, menu_item_id)
);
CREATE TABLE customer_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 conversation_id BIGINT NOT NULL REFERENCES conversations(id),
 recommendation_set_id BIGINT NOT NULL REFERENCES recommendation_sets(id),
 request_id UUID NOT NULL, request_fingerprint VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
 UNIQUE(user_id, request_id)
);
CREATE INDEX orders_user_recent ON customer_orders(user_id, id);
CREATE TABLE order_lines (
 order_id BIGINT NOT NULL REFERENCES customer_orders(id),
 menu_item_id VARCHAR(100) NOT NULL, name VARCHAR(200) NOT NULL,
 unit_price NUMERIC(10,2) NOT NULL, quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 line_total NUMERIC(12,2) NOT NULL, PRIMARY KEY (order_id, menu_item_id)
);
