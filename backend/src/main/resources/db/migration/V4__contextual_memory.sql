ALTER TABLE app_users ADD COLUMN memory_version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE contextual_memories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES app_users(id),
  source_message_id BIGINT NOT NULL UNIQUE REFERENCES messages(id),
  memory_version BIGINT NOT NULL,
  content VARCHAR(4000) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until TIMESTAMP WITH TIME ZONE,
  claim_token VARCHAR(36),
  error_category VARCHAR(40),
  embedding_model VARCHAR(100),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX memory_user_status ON contextual_memories(user_id,status,memory_version);
CREATE TABLE memory_outbox (
  memory_id BIGINT PRIMARY KEY REFERENCES contextual_memories(id),
  next_publish_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until TIMESTAMP WITH TIME ZONE,
  claim_token VARCHAR(36)
);
